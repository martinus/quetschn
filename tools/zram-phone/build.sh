#!/bin/bash
# build.sh <name> <src dir> <out dir>: the codec in <src dir> (a copy of src/) as a module for the Mi 9T's
# Linux 4.14, <out dir>/seqlz_<name>.ko, registering the crypto compressors seqlz-<name>-1 and so on,
# one per level, for zram. Built as the phone's kernel is, with NDK r21e's clang 9, the codec with -O3
# as lib/lz4, every function aligned to 64 bytes so that a change in one does not move the others. The
# module's symbol versions get the phone's CRCs (patch_versions.py), else 4.14 refuses it. OPT=-O2
# builds the codec with that instead of -O3, ALIGN=0 without -falign-functions=64, as the kernel builds
# arm64, where a function can start at any 4 bytes.
#
# Needs, in $MI9T_KERNEL (default ~/opt/mi9t-kernel):
#   src/            phoenix-r-oss of MiCode/Xiaomi_Kernel_OpenSource, 4.14.180 for the same SoC family
#   out/            that tree configured with the phone's /proc/config.gz and its version string, after
#                   make modules_prepare, so out/Module.symvers exists
#   hoststub/       headers the tree's host tools want and the machine lacks (openssl/)
#   phone-crcs.txt  the CRCs of the phone's own modules, from crcs.py
# and NDK r21e in $NDK_R21E (default ~/opt/android-ndk-r21e).
set -euo pipefail
[[ $# -eq 3 ]] || { sed -n '2,15p' "$0" >&2; exit 2; }
name=$1; src=$(realpath "$2"); out=$(realpath -m "$3")
here=$(cd "$(dirname "$0")" && pwd)
K=${MI9T_KERNEL:-$HOME/opt/mi9t-kernel}
T=${NDK_R21E:-$HOME/opt/android-ndk-r21e}/toolchains
rm -rf "$out"; mkdir -p "$out"
# the codec's files, whether src/ has it in one seqlz.c or split, and its tables, generated by the
# generator of the same tree; glue.c does not build them at load time any more
cp "$src"/seqlz*.c "$src"/*.h "$src"/*.inc "$out"/
gen=$src/../tools/gen-tables/gen-tables.sh
[[ -x $gen ]] || { echo "$src has no tools/gen-tables/ next to it, it is older than this build.sh" >&2; exit 1; }
"$gen" "$out/seqlz_tables.c"
objs=$(cd "$out" && ls seqlz*.c | sed 's/\.c$/.o/' | tr '\n' ' ')
sed -e "s/\"seqlz-\" #level/\"seqlz-$name-\" #level/g" "$here/glue.c" >"$out/glue.c"
grep -q "\"seqlz-$name-\" #level \"-generic\"" "$out/glue.c" || { echo "glue.c: no name to put $name into" >&2; exit 1; }
printf 'obj-m += seqlz_%s.o\nseqlz_%s-y := glue.o %s\n' "$name" "$name" "$objs" >"$out/Kbuild"
for o in $objs; do
    printf 'CFLAGS_%s += %s\n' "$o" "${OPT:--O3}" >>"$out/Kbuild"
done
[[ ${ALIGN:-64} == 0 ]] || printf 'ccflags-y += -falign-functions=%s\n' "${ALIGN:-64}" >>"$out/Kbuild"
export PATH=$T/llvm/prebuilt/linux-x86_64/bin:$T/aarch64-linux-android-4.9/prebuilt/linux-x86_64/bin:$PATH
make -C "$K/src" O="$K/out" ARCH=arm64 CC=clang CLANG_TRIPLE=aarch64-linux-gnu- CROSS_COMPILE=aarch64-linux-android- \
    HOSTCFLAGS=-I"$K/hoststub" M="$out" modules 2>&1 | grep -E ' error|warning:' || true
python3 "$here/patch_versions.py" "$K/phone-crcs.txt" "$K/out/Module.symvers" "$out/seqlz_$name.ko" >/dev/null
ls -l "$out/seqlz_$name.ko"
