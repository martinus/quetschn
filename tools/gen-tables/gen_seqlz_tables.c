/*
 * gen_seqlz_tables: seqlz's codes and decode tables, built from the code
 * lengths of src/seqlz_default_tables.c and src/seqlz_lit_sets.c and printed
 * as C, the seqlz_tables.c that every build of seqlz compiles. gen-tables.sh
 * builds it for the build host and runs it. The kernel's copy is
 * lib/seqlz/gen_seqlz_tables.c: src/seqlz_codes.c, and this from the line
 * below on.
 */
#include <stdio.h>

#include "seqlz.h"

/* ---- the tables as C, for seqlz_tables.c ---- */

/* the tables built from the lengths, before they are printed */
static struct seqlz_tables tables;

/*
 * The numbers at p, size bytes in all and each of the given bytes, as an
 * initializer of the field name, in hexadecimal and at most 80 columns wide
 */
static void print_array(const char *name, const void *p, size_t size,
			size_t bytes)
{
	const size_t n = size / bytes;
	/* "0x", the digits and ", " in the 64 columns after two tabs */
	const unsigned int per_line = (64 + 1) / (2 * bytes + 4);
	size_t k;

	printf("\t%s = {", name);
	for (k = 0; k < n; k++) {
		unsigned long long v = bytes == 2 ? ((const u16 *)p)[k] :
				       bytes == 4 ? ((const u32 *)p)[k] :
						    ((const u64 *)p)[k];

		printf(k % per_line ? " 0x%0*llx," : "\n\t\t0x%0*llx,",
		       (int)(2 * bytes), v);
	}
	printf("\n\t},\n");
}

int main(void)
{
	char name[64];
	unsigned int k;

	if (seqlz_tables_build(&tables, &seqlz_default_lengths)) {
		fprintf(stderr, "gen_seqlz_tables: the lengths are invalid\n");
		return 1;
	}
	/* in the build's tree only, as lib/crc's tables */
	printf("/*\n"
	       " * Generated by gen_seqlz_tables from the code lengths. Do not edit.\n"
	       " */\n"
	       "#include \"seqlz_tables.h\"\n\n"
	       "const struct seqlz_tables seqlz_tables = {\n");
	print_array(".token.decode", tables.token.decode,
		    sizeof(tables.token.decode),
		    sizeof(tables.token.decode[0]));
	print_array(".token.enc", tables.token.enc, sizeof(tables.token.enc),
		    sizeof(tables.token.enc[0]));
	for (k = 0; k < SEQLZ_LIT_SETS; k++) {
		snprintf(name, sizeof(name), ".lit[%u].decode", k);
		print_array(name, tables.lit[k].decode,
			    sizeof(tables.lit[k].decode),
			    sizeof(tables.lit[k].decode[0]));
		snprintf(name, sizeof(name), ".lit[%u].enc", k);
		print_array(name, tables.lit[k].enc, sizeof(tables.lit[k].enc),
			    sizeof(tables.lit[k].enc[0]));
	}
	print_array(".lit_cost", tables.lit_cost, sizeof(tables.lit_cost),
		    sizeof(tables.lit_cost[0]));
	print_array(".own.decode", tables.own.decode, sizeof(tables.own.decode),
		    sizeof(tables.own.decode[0]));
	print_array(".own.enc", tables.own.enc, sizeof(tables.own.enc),
		    sizeof(tables.own.enc[0]));
	print_array(".own.quad", tables.own.quad, sizeof(tables.own.quad),
		    sizeof(tables.own.quad[0]));
	print_array(".ll.decode", tables.ll.decode, sizeof(tables.ll.decode),
		    sizeof(tables.ll.decode[0]));
	print_array(".ll.enc", tables.ll.enc, sizeof(tables.ll.enc),
		    sizeof(tables.ll.enc[0]));
	print_array(".ml.decode", tables.ml.decode, sizeof(tables.ml.decode),
		    sizeof(tables.ml.decode[0]));
	print_array(".ml.enc", tables.ml.enc, sizeof(tables.ml.enc),
		    sizeof(tables.ml.enc[0]));
	printf("};\n");
	return 0;
}
